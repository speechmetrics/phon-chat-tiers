#!/usr/bin/env python3
"""Generate Appendix D (IPA characters) of the specification. Run from the
repository root:
    python3 scripts/gen_ipa_table.py
The character list is data/ipa-characters.tsv: one accepted character per
line, its code point and its role. The tables between the BEGIN and END
markers in spec/phon-chat-tiers.md are rewritten from it; never edit them
by hand. Unicode names come from Python's unicodedata.

The data was taken from Phon's IPA parser as shipped in Phon 4.2: every Unicode code point was passed through its lexer, and each one
it accepts as a token of its own is listed, except the Phon-internal
characters that Appendix D excludes. The colon (U+003A) of a timed pause
token is added by hand: the parser reads it only as part of other tokens."""
from __future__ import annotations
import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "ipa-characters.tsv"
SPEC = ROOT / "spec" / "phon-chat-tiers.md"
BEGIN = "<!-- BEGIN ipa-characters: generated by scripts/gen_ipa_table.py -->"
END = "<!-- END ipa-characters -->"

# Table order and headings. Each role in the data must appear here.
SECTIONS = [
    ("D.1 Base glyphs", [
        ("consonant", "Consonants"),
        ("vowel", "Vowels"),
        ("glide", "Glides"),
        ("cover", "Cover symbols"),
    ]),
    ("D.2 Diacritics", [
        ("prefix", "Prefix diacritics"),
        ("suffix", "Suffix diacritics"),
        ("combining", "Combining diacritics"),
        ("role-reversal", "Role reversal"),
        ("length", "Length"),
        ("ligature", "Ligatures"),
    ]),
    ("D.3 Tone numbers", [
        ("tone", None),
    ]),
    ("D.4 Marks and separators", [
        ("stress", "Stress"),
        ("syllable-boundary", "Syllable boundary"),
        ("intra-word-pause", "Intra-word pause"),
        ("compound-marker", "Compound-word marker"),
        ("sandhi", "Sandhi"),
        ("intonation-group", "Intonation group"),
        ("phonetic-group", "Phonetic group"),
        ("space", "Word separator"),
    ]),
    ("D.5 Pause tokens", [
        ("pause", None),
    ]),
]

# Combining marks are shown on a dotted circle so they render alone.
CARRIER = "◌"


def load() -> dict[str, list[int]]:
    roles: dict[str, list[int]] = {}
    for n, line in enumerate(DATA.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        cp_text, role = line.split("\t")
        if not cp_text.startswith("U+"):
            sys.exit(f"{DATA}:{n}: code point must be written U+XXXX")
        roles.setdefault(role, []).append(int(cp_text[2:], 16))
    return roles


def glyph(cp: int) -> str:
    ch = chr(cp)
    if cp == 0x20:
        return "(space)"
    if cp == 0x7C:
        return "`\\|`"
    shown = CARRIER + ch if unicodedata.combining(ch) or unicodedata.category(ch) == "Mn" else ch
    return f"`{shown}`"


def table(cps: list[int]) -> list[str]:
    rows = ["| Code point | Character | Unicode name |",
            "|------------|-----------|--------------|"]
    for cp in sorted(cps):
        name = unicodedata.name(chr(cp), None)
        if name is None:
            sys.exit(f"U+{cp:04X} has no Unicode name in this Python's unicodedata")
        rows.append(f"| U+{cp:04X} | {glyph(cp)} | {name} |")
    return rows


def render(roles: dict[str, list[int]]) -> str:
    known = {role for _, subs in SECTIONS for role, _ in subs}
    unknown = set(roles) - known
    if unknown:
        sys.exit(f"{DATA}: roles with no section: {', '.join(sorted(unknown))}")
    total = sum(len(v) for v in roles.values())
    out = [BEGIN, "", f"{total} characters in all.", ""]
    for heading, subs in SECTIONS:
        count = sum(len(roles.get(role, [])) for role, _ in subs)
        out += [f"### {heading} ({count})", ""]
        for role, sub in subs:
            cps = roles.get(role, [])
            if not cps:
                sys.exit(f"{DATA}: no characters with role {role}")
            if sub:
                out += [f"**{sub}** ({len(cps)})", ""]
            out += table(cps) + [""]
    out.append(END)
    return "\n".join(out)


def main() -> None:
    spec = SPEC.read_text(encoding="utf-8")
    start, end = spec.find(BEGIN), spec.find(END)
    if start < 0 or end < start:
        sys.exit(f"{SPEC}: BEGIN/END markers for the IPA tables not found")
    new = spec[:start] + render(load()) + spec[end + len(END):]
    if new != spec:
        SPEC.write_text(new, encoding="utf-8")
        print(f"updated {SPEC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
